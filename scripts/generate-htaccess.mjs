/**
 * Writes `out/.htaccess` after a static export.
 *
 * The canonical origin is not duplicated here: it is read back from the
 * `Sitemap:` line of the `robots.txt` the app itself generated, so the Apache
 * redirects and the canonical URLs in the HTML can never disagree. A build that
 * is not indexable (staging/preview/dev) produces a robots.txt without that
 * line — such builds get no host canonicalisation and a site-wide
 * `X-Robots-Tag: noindex` instead.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const OUT_DIR = path.resolve('out');

async function readCanonicalOrigin() {
    try {
        const robots = await readFile(path.join(OUT_DIR, 'robots.txt'), 'utf8');
        const match = robots.match(/^Sitemap:\s*(\S+)$/m);
        return match ? new URL(match[1]).origin : null;
    } catch {
        return null;
    }
}

function canonicalHostRules(origin) {
    const { host, protocol } = new URL(origin);
    const isWww = host.startsWith('www.');
    const otherHost = isWww ? host.slice(4) : `www.${host}`;
    const escapedOther = otherHost.replace(/\./g, '\\.');

    return `
# --- Canonical protocol + host (one hop, 301) --------------------------------
# Both rules redirect straight to the canonical origin, so http://${otherHost}/x
# reaches ${origin}/x in a single hop instead of a chain.
# X-Forwarded-Proto is honoured so a TLS-terminating proxy cannot cause a loop.
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !=https
RewriteRule ^(.*)$ ${protocol}//${host}/$1 [R=301,L]

RewriteCond %{HTTP_HOST} ^${escapedOther}$ [NC]
RewriteRule ^(.*)$ ${protocol}//${host}/$1 [R=301,L]
`;
}

const NOINDEX_HEADER = `
# Non-production build: keep the whole host out of search engines.
<IfModule mod_headers.c>
    Header set X-Robots-Tag "noindex, nofollow"
</IfModule>
`;

async function main() {
    const origin = await readCanonicalOrigin();

    const contents = `# Generated by scripts/generate-htaccess.mjs — do not edit by hand.
# Regenerated on every \`npm run build:static\`.

# /services is both a page (services.html) and a directory (the service pages).
# With DirectorySlash on, mod_dir would 301 the canonical /services to /services/
# while the rules below 301 /services/ back — an infinite loop. Turning it off
# lets services.html win. (Requires AllowOverride Indexes or All, which cPanel
# grants by default.)
<IfModule mod_dir.c>
    DirectorySlash Off
</IfModule>

<IfModule mod_rewrite.c>
RewriteEngine On
${origin ? canonicalHostRules(origin) : ''}
# --- Trailing slashes --------------------------------------------------------
# The export is built with \`trailingSlash: false\`; /about-us/ 301s to /about-us
# so a page is never reachable under two URLs. Real asset directories that have
# no <name>.html twin (e.g. /_next/static/) are left alone.
RewriteCond %{DOCUMENT_ROOT}/$1.html -f [OR]
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^(.+)/$ /$1 [R=301,L]

# --- Extension-less URLs -----------------------------------------------------
# Only "/" is the home page: /index and /index.html 301 to it.
RewriteCond %{THE_REQUEST} \\s/+(.*?)index(\\.html)?[\\s?] [NC]
RewriteRule ^ /%1 [R=301,L,NE]

# /about-us.html is the file on disk, /about-us is the canonical URL.
RewriteCond %{THE_REQUEST} \\s/+([^?\\s]*?)\\.html[\\s?] [NC]
RewriteRule ^ /%1 [R=301,L,NE]

# Serve <path>.html for the clean URL without changing the address bar.
# \`-d\` is deliberately not excluded: /services is both a directory (the service
# pages) and a page (services.html), and the page must win — otherwise mod_dir
# would 301 the canonical /services to /services/.
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{DOCUMENT_ROOT}/$1.html -f
RewriteRule ^(.+?)/?$ /$1.html [L]

# --- Legacy URLs -------------------------------------------------------------
# Add 301s for renamed or removed pages here, e.g.
#   RewriteRule ^old-slug$ /services/new-slug [R=301,L]
# Never redirect an unrelated removed page to the home page: let it 404 (or
# return 410 with \`RewriteRule ^gone-page$ - [G]\`).
</IfModule>

# --- Not found ---------------------------------------------------------------
ErrorDocument 404 /404.html

<IfModule mod_headers.c>
    # RSC payload twins (\`/about-us.txt\`) exist only for client navigation.
    # They stay crawlable so this header can be seen, but must not be indexed.
    <FilesMatch "\\.txt$">
        Header set X-Robots-Tag "noindex"
    </FilesMatch>
    <Files "robots.txt">
        Header unset X-Robots-Tag
    </Files>

    Header always set X-Content-Type-Options "nosniff"
    Header always set Referrer-Policy "strict-origin-when-cross-origin"
    Header always set X-Frame-Options "SAMEORIGIN"
${origin?.startsWith('https://') ? '    Header always set Strict-Transport-Security "max-age=31536000"\n' : ''}</IfModule>
${origin ? '' : NOINDEX_HEADER}
# --- Caching -----------------------------------------------------------------
<IfModule mod_expires.c>
    ExpiresActive On
    # Hashed build assets are immutable.
    <FilesMatch "\\.(js|css|woff2?|otf|ttf)$">
        ExpiresDefault "access plus 1 year"
    </FilesMatch>
    <FilesMatch "\\.(webp|avif|png|jpe?g|gif|svg|ico)$">
        ExpiresDefault "access plus 30 days"
    </FilesMatch>
    <FilesMatch "\\.(html|xml|txt|webmanifest)$">
        ExpiresDefault "access plus 0 seconds"
    </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
    AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json image/svg+xml
</IfModule>
`;

    await writeFile(path.join(OUT_DIR, '.htaccess'), contents, 'utf8');
    console.log(
        origin
            ? `[htaccess] written for ${origin}`
            : '[htaccess] written without canonical host (non-indexable build)',
    );
}

main().catch((error) => {
    console.error('[htaccess] generation failed:', error);
    process.exitCode = 1;
});
